public class ILEmitZeroAllocationTests
{
    [Fact]
    public void JsonModeWithCache_DynamicSerializer_ShouldSerializeCorrectly()
    {
        // Arrange
        var testObj = new AccountRModel
        {
            Id = Guid.NewGuid(),
            UserName = "test_user",
            Password = "hashed_password",
            FullName = "Test User Fullname",
            Email = "test@npon.vn",
            PhoneNumber = "0987654321",
            Status = EAccountStatus.Active,
            Permission = EPermission.Administrator
        };

        // Act - Uses DynamicMethod and IL.Emit generated bytecode
        var jsonWithNulls = JsonModeWithCache.ToJsonAsNull(testObj);
        var jsonWithoutNulls = JsonModeWithCache.ToJson(testObj);

        // Assert
        Assert.NotNull(jsonWithNulls);
        Assert.Contains("test_user", jsonWithNulls);
        Assert.Contains("test@npon.vn", jsonWithNulls);

        Assert.NotNull(jsonWithoutNulls);
        Assert.Contains("test_user", jsonWithoutNulls);
    }

    [Fact]
    public void DynamicObjectMapper_ILEmit_ShouldMapRowWrapperToObjectWithoutReflection()
    {
        // Arrange
        var expectedId = Guid.NewGuid();
        var cells = new Dictionary<string, INpOnCell>
        {
            ["id"] = new NpOnCell<Guid>(expectedId, DbType.Guid, "uuid", true),
            ["username"] = new NpOnCell<string>("leduc", DbType.String, "varchar"),
            ["password"] = new NpOnCell<string>("secret_pass", DbType.String, "varchar"),
            ["full_name"] = new NpOnCell<string>("Le Duc", DbType.String, "varchar"),
            ["email"] = new NpOnCell<string>("leduc@example.com", DbType.String, "varchar"),
            ["phone_number"] = new NpOnCell<string>("0912345678", DbType.String, "varchar"),
            ["status"] = new NpOnCell<int>((int)EAccountStatus.Active, DbType.Int32, "int4"),
            ["permission"] = new NpOnCell<int>((int)EPermission.Administrator, DbType.Int32, "int4")
        };

        var row = new MockRowWrapper(cells);
        var table = new MockTableWrapper([row]);

        // Act - Maps using DynamicMethod IL generation
        var results = table.ToList<AccountRModel>();

        // Assert
        Assert.NotNull(results);
        Assert.Single(results);

        var model = results[0];
        Assert.Equal(expectedId, model.Id);
        Assert.Equal("leduc", model.UserName);
        Assert.Equal("secret_pass", model.Password);
        Assert.Equal("Le Duc", model.FullName);
        Assert.Equal("leduc@example.com", model.Email);
        Assert.Equal("0912345678", model.PhoneNumber);
        Assert.Equal(EAccountStatus.Active, model.Status);
        Assert.Equal(EPermission.Administrator, model.Permission);
    }

    [Fact]
    public void DynamicObjectMapper_ILEmit_NullValues_ShouldBeHandledSafely()
    {
        // Arrange: Missing optional columns or null cell values
        var expectedId = Guid.NewGuid();
        var cells = new Dictionary<string, INpOnCell>
        {
            ["id"] = new NpOnCell<Guid>(expectedId, DbType.Guid, "uuid", true),
            ["username"] = new NpOnCell<string>("null_test", DbType.String, "varchar"),
            ["password"] = new NpOnCell<string>("pass123", DbType.String, "varchar"),
            ["full_name"] = new NpOnCell<string>(null, DbType.String, "varchar"), // null
            ["email"] = new NpOnCell<string>(null, DbType.String, "varchar"),
            ["status"] = new NpOnCell<int>((int)EAccountStatus.Unactive, DbType.Int32, "int4")
        };

        var row = new MockRowWrapper(cells);
        var table = new MockTableWrapper([row]);

        // Act
        var results = table.ToList<AccountRModel>();

        // Assert
        Assert.NotNull(results);
        Assert.Single(results);
        var model = results[0];
        Assert.Equal("null_test", model.UserName);
        Assert.Null(model.FullName);
        Assert.Null(model.Email);
        Assert.Equal(EAccountStatus.Unactive, model.Status);
    }

    [Fact]
    public void DynamicObjectMapper_VectorizedPages_ShouldMapWithZeroBoxing()
    {
        // Arrange
        var expectedId = Guid.NewGuid();
        var idBlock = new Common.Extensions.NpOn.ICommonDb.DbResults.Blocks.GuidBlock(1);
        idBlock.Buffer[0] = expectedId;

        var userBlock = new Common.Extensions.NpOn.ICommonDb.DbResults.Blocks.StringBlock(1);
        userBlock.Buffer[0] = "vector_user";

        var passBlock = new Common.Extensions.NpOn.ICommonDb.DbResults.Blocks.StringBlock(1);
        passBlock.Buffer[0] = "vector_pass";

        var statusBlock = new Common.Extensions.NpOn.ICommonDb.DbResults.Blocks.Int32Block(1);
        statusBlock.Buffer[0] = (int)EAccountStatus.Active;

        var nameMap = new Dictionary<string, int>
        {
            ["id"] = 0,
            ["username"] = 1,
            ["password"] = 2,
            ["status"] = 3
        };

        var page = new Common.Extensions.NpOn.ICommonDb.DbResults.Blocks.NpOnDataPage(
            1, [idBlock, userBlock, passBlock, statusBlock], nameMap);

        var table = new MockVectorTableWrapper([page], nameMap);

        // Act
        var results = table.ToList<AccountRModel>();

        // Assert
        Assert.NotNull(results);
        Assert.Single(results);
        var model = results[0];
        Assert.Equal(expectedId, model.Id);
        Assert.Equal("vector_user", model.UserName);
        Assert.Equal("vector_pass", model.Password);
        Assert.Equal(EAccountStatus.Active, model.Status);

        page.Dispose();
    }
}
